                lblTitulo.setFont(fontTitulo);
                lblTitulo.setForeground(colorBlanco);
                lblTitulo.setVerticalAlignment(javax.swing.SwingConstants.BOTTOM);

                lblCount.setFont(fontContador);
                lblCount.setForeground(colorBlanco);
                lblCount.setVerticalAlignment(javax.swing.SwingConstants.TOP);

                panelTexto.add(lblTitulo);
                panelTexto.add(lblCount);

                tarjeta.add(icono, java.awt.BorderLayout.WEST);
                tarjeta.add(panelTexto, java.awt.BorderLayout.CENTER);

                hostPanel.add(tarjeta, java.awt.BorderLayout.CENTER);
