// Clase interna para panel con gradiente
class PanelGradiente extends javax.swing.JPanel {

    private java.awt.Color color1;
    private java.awt.Color color2;

    public PanelGradiente(java.awt.Color color1, java.awt.Color color2) {
        this.color1 = color1;
        this.color2 = color2;
        setOpaque(false);
    }

    @Override
    protected void paintComponent(java.awt.Graphics g) {
        java.awt.Graphics2D g2 = (java.awt.Graphics2D) g;
        g2.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);

        java.awt.GradientPaint gp = new java.awt.GradientPaint(0, 0, color1, getWidth(), getHeight(), color2);
        g2.setPaint(gp);
        g2.fillRoundRect(0, 0, getWidth(), getHeight(), 15, 15);

        super.paintComponent(g);
    }
}

// Clase interna para dibujar iconos vectoriales simples
class IconoPanel extends javax.swing.JPanel {

    private String tipo;

    public IconoPanel(String tipo) {
        this.tipo = tipo;
        setOpaque(false);
    }

    @Override
    protected void paintComponent(java.awt.Graphics g) {
        super.paintComponent(g);
        java.awt.Graphics2D g2 = (java.awt.Graphics2D) g;
        g2.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
        g2.setColor(new java.awt.Color(255, 255, 255, 200));
        g2.setStroke(new java.awt.BasicStroke(2));

        int w = getWidth();
        int h = getHeight();
        int cx = w / 2;
        int cy = h / 2;

        switch (tipo) {
            case "EMPLEADOS":
            case "CLIENTES":
                g2.fillOval(cx - 6, cy - 12, 12, 12);
                g2.fillArc(cx - 12, cy + 2, 24, 20, 0, 180);
                break;
            case "PROVEEDORES":
                break;
            case "PRODUCTOS":
                g2.fillRect(cx - 12, cy - 10, 24, 20);
                g2.setColor(new java.awt.Color(255, 255, 255, 100));
                g2.drawLine(cx - 12, cy, cx + 12, cy);
                g2.drawLine(cx, cy - 10, cx, cy + 10);
                break;
            case "VENTAS":
                g2.setFont(new java.awt.Font("Segoe UI", 1, 24));
                java.awt.FontMetrics fm = g2.getFontMetrics();
                int textW = fm.stringWidth("$");
                int textH = fm.getAscent();
                g2.drawString("$", cx - (textW / 2), cy + (textH / 4));
                g2.drawOval(cx - 15, cy - 15, 30, 30);
                break;
        }
    }
}
